def apply_edits(text, pairs, what):
    for old, new in pairs:
        if new in text and old not in text:
            continue        # already corrected upstream; nothing to do
        if text.count(old) != 1:
            raise SystemExit(
                f"site.py: {what}: expected exactly one copy of {old[:60]!r}, "
                f"found {text.count(old)}. The snapshot changed; re-check the "
                f"correction in CONTENT_EDITS/SCRIPT_EDITS before building.")
        text = text.replace(old, new, 1)
    return text


def read_source(src):
    path = OWN / src[4:] if src.startswith("own/") else SRC / src
    text = path.read_text(encoding="utf-8")
    if src in CONTENT_EDITS:
        text = apply_edits(text, CONTENT_EDITS[src], src)
    return BeautifulSoup(text, "html.parser")


def extract(src, page):
    """The source page's body content, minus its site navigation, with links
    mapped. Returns (content soup fragment, scripts, head styles, description)."""
    repo = src.split("/")[0]
    soup = read_source(src)
    desc = soup.find("meta", attrs={"name": "description"})
    desc = desc["content"] if desc else ""
    styles = [s.string or "" for s in soup.head.find_all("style")] if soup.head else []
    body = soup.body
    for c in body.find_all(string=lambda t: isinstance(t, Comment)):
        c.extract()
    chrome = CHROME[repo]
    kept = []
    for sel in chrome["keep"]:
        for el in body.select(sel):
            kept.append(el.extract())
    for sel in chrome["remove"]:
        for el in body.select(sel):
            el.decompose()
    for sel in chrome["unwrap"]:
        for el in body.select(sel):
            el.unwrap()
    scripts = []
    for s in body.find_all("script"):
        scripts.append({"src": s.get("src"), "body": s.string or "", "attrs": {k: v for k, v in s.attrs.items() if k != "src"}})
        s.decompose()
    for m in body.find_all("main"):
        m.name = "div"
        m["class"] = ["src-main"] + m.get("class", [])
        if m.get("id") == "main-content":
            del m["id"]
    for f in body.find_all("footer"):
        f.name = "div"
        f["class"] = ["src-footer"] + f.get("class", [])
    if kept:
        box = soup.new_tag("div", attrs={"class": "src-footer src-footer--notes"})
        for el in kept:
            el.name = "p"
            box.append(el)
        body.append(box)
    for tag in body.find_all(["a", "area"]):
        if tag.get("href"):
            tag["href"] = map_href(tag["href"], repo, page)
    return soup, body, scripts, styles, desc


def dash_tree(node, where):
    for t in node.find_all(string=True):
        if isinstance(t, Comment):
            continue
        if EM in t:
            t.replace_with(NavigableString(fix_dashes(str(t), where)))
    for tag in node.find_all(True):
        for k, v in list(tag.attrs.items()):
            if isinstance(v, str) and EM in v:
                tag[k] = fix_dashes(v, where + f" ({k})")


def level_headings(wrap):
    """No skipped heading levels (SEO review S4): a heading more than one level
    below the one before it moves up. Its look is kept with a class."""
    prev = 1
    for h in wrap.find_all(re.compile("^h[1-6]$")):
        lvl = int(h.name[1])
        if lvl > prev + 1:
            h["class"] = h.get("class", []) + [f"site-h{lvl}"]
            h.name = f"h{prev + 1}"
            lvl = prev + 1
        prev = lvl


