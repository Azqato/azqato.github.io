def rel(from_path, to_path):
    """Relative link from one page to another (or to the site root, "")."""
    if not to_path:
        return "../" * from_path.count("/")
    return posixpath.relpath(to_path, posixpath.dirname(from_path) or ".")


def map_href(href, repo, page):
    if not href or href.startswith(("#", "mailto:", "javascript:", "data:")):
        return href
    base, frag = (href.split("#", 1) + [""])[:2]
    frag = "#" + frag if "#" in href else ""
    m = COMPOSER_OLD.match(base)
    if m:
        return "https://composeratlas.com/" + m.group(1) + frag
    if base.startswith("http"):
        key = ("abs", base.rstrip("/") if base.rstrip("/") + "/" != base or ("abs", base) not in LINKS else base)
        for k in (("abs", base), ("abs", base.rstrip("/"))):
            if k in LINKS:
                return link_to(page, LINKS[k], frag)
        return href
    if repo == "azqato.github.io":
        name = base[:-5] if base.endswith(".html") else base
        if name == "index":
            return "https://azqato.com/" + frag
        if name == "invests":
            return rel(page, "index.html") + frag
        return f"https://azqato.com/{name}{frag}"
    if (repo, base) in LINKS:
        return link_to(page, LINKS[(repo, base)], frag)
    if base == "" and frag:
        return frag
    return href


def link_to(page, target, frag):
    """A link to a page that may be a section of another (COMBINE): the link's
    own #fragment wins, otherwise the section's."""
    path, _, sec = target.partition("#")
    return rel(page, path) + (frag or ("#" + sec if sec else ""))


def slug(text, used):
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:48] or "section"
    out, n = s, 2
    while out in used:
        out, n = f"{s}-{n}", n + 1
    used.add(out)
    return out


