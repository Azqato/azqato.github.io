def combine_part(page, wrap, src, sid, heading, scripts, styles):
    """Append another source page to this one as a section (COMBINE)."""
    soup, body, scripts2, styles2, _ = extract(src, page)
    part = soup.new_tag("section", attrs={"class": "site-part", "id": sid, "aria-labelledby": f"{sid}-title"})
    for n in list(body.children):
        part.append(n.extract())
    if sid == "custom":
        # The reading and tier first (UI review), then the ticker inputs, then the
        # chart and table they drive (author's request, 2026-10-02).
        part.find(id="chart-section").insert_before(part.find(id="customize").extract())
    rename = COMBINE_RENAME.get(sid, [])
    for el in part.find_all(id=True):
        if el["id"] in rename:
            el["id"] = f"{sid}-{el['id']}"
    for attr in ("for", "aria-labelledby", "aria-describedby", "aria-controls", "href"):
        for el in part.find_all(attrs={attr: True}):
            v = el[attr]
            if attr == "href":
                if v.startswith("#") and v[1:] in rename:
                    el[attr] = f"#{sid}-{v[1:]}"
            else:
                el[attr] = " ".join(f"{sid}-{x}" if x in rename else x for x in v.split())
    # One h1 per page: the part's h1 becomes its h2 and the rest move down a level.
    for lvl in (5, 4, 3, 2):
        for h in part.find_all(f"h{lvl}"):
            h.name = f"h{lvl + 1}"
    h1 = part.find("h1")
    if h1:
        h1.name = "h2"
        h1["id"] = f"{sid}-title"
    else:
        h = soup.new_tag("h2", attrs={"id": f"{sid}-title"})
        h.string = heading
        part.insert(0, h)
    wrap.append(part)
    seen = {x["src"] for x in scripts if x["src"]}
    for x in scripts2:
        if x["src"]:
            if x["src"] in seen:
                continue
            seen.add(x["src"])
        elif rename:
            js = x["body"]
            for r in rename:
                js = js.replace(f"getElementById('{r}')", f"getElementById('{sid}-{r}')")
            js = js.replace("initChart('allocationChart'", f"initChart('{sid}-allocationChart'")
            x = dict(x, body=js)
        scripts.append(x)
    return scripts, styles + [x for x in styles2 if x not in styles]


def split_page(page, wrap):
    """A landing page or its Method page (SPLIT)."""
    landing = page in SPLIT
    cfg = SPLIT[page] if landing else SPLIT[METHOD_OF[page]]

    def find(key):
        hit = wrap.find(id=key) or wrap.find(class_=key)
        assert hit, (page, key)
        return hit
    moved = [find(k) for k in cfg["move"]]
    if landing:
        ids = sorted({el["id"] for m in moved for el in [m] + m.find_all(id=True)})
        for m in moved:
            m.decompose()
        r = rel(page, "")
        cards = "".join(f'<a class="pp-card" href="{r}{u}"><span class="pp-card-kicker">{i}</span>'
                        f'<strong>{esc(t)}</strong><span>{esc(d)}</span></a>'
                        for i, (u, t, d) in enumerate(cfg["cards"], 1))
        button = (f'<p class="site-landing-start"><a class="pp-btn pp-btn--solid" href="{r}{cfg["button"][1]}">{esc(cfg["button"][0])}</a></p>'
                  if cfg["button"] else "")
        method = rel(page, cfg["method"])
        forward = ("<script>(function () { var ids = " + json.dumps(ids) + "; var h = decodeURIComponent(location.hash.slice(1));"
                   f' if (h && ids.indexOf(h) > -1 && !document.getElementById(h)) location.replace("{method}#" + h); }})();</script>')
        tag, key = cfg["after"]
        anchor = wrap.find(tag, id=key) or wrap.find(tag, class_=key)
        anchor.insert_after(BeautifulSoup(f'<div class="site-landing">{button}<div class="pp-cards">{cards}</div></div>{forward}', "html.parser"))
    else:
        for key in cfg["drop"]:
            find(key).decompose()


def merge_footers(wrap, repo):
    """One footer per page (UI review). The source footers that only repeat the
    site footer ("Built by Azqato", "Educational use only. Not financial advice.")
    stay in the page, hidden (class site-dup). The VIX pages' disclaimer and
    copyright lines move into the site footer; their call-to-action stays."""
    notes = []
    for f in wrap.select(".src-footer"):
        disc = f.select_one(".footer-disclaimer")
        if repo == "vix" and disc:
            for p in disc.find_all("p"):
                p["class"] = p.get("class", []) + ["site-footer-note"]
                if p.get_text(" ", strip=True).startswith("Built by"):
                    p["class"] = p["class"] + ["site-dup"]
                notes.append(str(p))
            disc.decompose()
        elif not f.select_one(".footer-cta"):
            f["class"] = f.get("class", []) + ["site-dup"]
    # A combined page (COMBINE) carries each source's footer: a repeat of an
    # earlier one stays in the page, hidden like the other duplicates.
    seen = set()
    for f in wrap.select(".src-footer"):
        t = f.get_text(" ", strip=True)
        if t in seen and "site-dup" not in f.get("class", []):
            f["class"] = f.get("class", []) + ["site-dup"]
        seen.add(t)
    return "".join("\n    " + n for n in dict.fromkeys(notes))


def index_page(page, label, group, wrap, search):
    pi = len(search["pages"])
    search["pages"].append({"u": page, "t": label if page != "index.html" else "Home", "g": group or "Home"})
    entry = {"p": pi, "h": label, "a": "", "x": ""}
    for el in wrap.find_all(["h1", "h2", "h3", "p", "li", "td", "th", "dt", "dd", "button", "figcaption", "summary"]):
        if el.name in ("h2", "h3") and el.get("id"):
            search["entries"].append(entry)
            entry = {"p": pi, "h": el.get_text(" ", strip=True), "a": el["id"], "x": ""}
        elif el.name != "h1" and not el.find(["p", "li", "td", "dt", "dd"]):
            entry["x"] += " " + el.get_text(" ", strip=True)
    search["entries"].append(entry)


