def rel(from_path, to_path):
    """Relative link from one page to another (or to the site root, "")."""
    if not to_path:
        return "../" * from_path.count("/")
    return posixpath.relpath(to_path, posixpath.dirname(from_path) or ".")


def map_href(href, repo, page):
    if not href or href.startswith(("#", "mailto:", "javascript:", "data:")):
        return href
    base, frag = (href.split("#", 1) + [""])[:2]
    frag = "#" + frag if "#" in href else ""
    m = COMPOSER_OLD.match(base)
    if m:
        return "https://composeratlas.com/" + m.group(1) + frag
    if base.startswith("http"):
        key = ("abs", base.rstrip("/") if base.rstrip("/") + "/" != base or ("abs", base) not in LINKS else base)
        for k in (("abs", base), ("abs", base.rstrip("/"))):
            if k in LINKS:
                return rel(page, LINKS[k]) + frag
        return href
    if repo == "azqato.github.io":
        name = base[:-5] if base.endswith(".html") else base
        if name == "index":
            return "https://azqato.com/" + frag
        if name == "invests":
            return rel(page, "index.html") + frag
        return f"https://azqato.com/{name}{frag}"
    if (repo, base) in LINKS:
        return rel(page, LINKS[(repo, base)]) + frag
    if base == "" and frag:
        return frag
    return href


def slug(text, used):
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")[:48] or "section"
    out, n = s, 2
    while out in used:
        out, n = f"{s}-{n}", n + 1
    used.add(out)
    return out


def read_source(src):
    return BeautifulSoup((SRC / src).read_text(encoding="utf-8"), "html.parser")


def extract(src, page):
    """The source page's body content, minus its site navigation, with links
    mapped. Returns (content soup fragment, scripts, head styles, description)."""
    repo = src.split("/")[0]
    soup = read_source(src)
    desc = soup.find("meta", attrs={"name": "description"})
    desc = desc["content"] if desc else ""
    styles = [s.string or "" for s in soup.head.find_all("style")] if soup.head else []
    body = soup.body
    for c in body.find_all(string=lambda t: isinstance(t, Comment)):
        c.extract()
    chrome = CHROME[repo]
    kept = []
    for sel in chrome["keep"]:
        for el in body.select(sel):
            kept.append(el.extract())
    for sel in chrome["remove"]:
        for el in body.select(sel):
            el.decompose()
    for sel in chrome["unwrap"]:
        for el in body.select(sel):
            el.unwrap()
    scripts = []
    for s in body.find_all("script"):
        scripts.append({"src": s.get("src"), "body": s.string or "", "attrs": {k: v for k, v in s.attrs.items() if k != "src"}})
        s.decompose()
    for m in body.find_all("main"):
        m.name = "div"
        m["class"] = ["src-main"] + m.get("class", [])
        if m.get("id") == "main-content":
            del m["id"]
    for f in body.find_all("footer"):
        f.name = "div"
        f["class"] = ["src-footer"] + f.get("class", [])
    if kept:
        box = soup.new_tag("div", attrs={"class": "src-footer src-footer--notes"})
        for el in kept:
            el.name = "p"
            box.append(el)
        body.append(box)
    for tag in body.find_all(["a", "area"]):
        if tag.get("href"):
            tag["href"] = map_href(tag["href"], repo, page)
    return soup, body, scripts, styles, desc


def dash_tree(node, where):
    for t in node.find_all(string=True):
        if isinstance(t, Comment):
            continue
        if EM in t:
            t.replace_with(NavigableString(fix_dashes(str(t), where)))
    for tag in node.find_all(True):
        for k, v in list(tag.attrs.items()):
            if isinstance(v, str) and EM in v:
                tag[k] = fix_dashes(v, where + f" ({k})")


def ensure_ids(article):
    used = {el["id"] for el in article.find_all(id=True)}
    for h in article.find_all(["h2", "h3"]):
        if not h.get("id"):
            h["id"] = slug(h.get_text(" ", strip=True), used)


