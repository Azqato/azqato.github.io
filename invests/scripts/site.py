# ---------- Em dashes (Question 14) ----------

DASH = re.compile(r"(\S?)(\s*)\u2014(\s*)(?=(\S?))")


def fix_dashes(text, where):
    """Replace em dashes used as punctuation between words: spaced ones with a
    single hyphen, unspaced ones with a comma (Writing Style). A lone dash that
    stands for a missing value, such as the screener's "(-)" written with an
    em dash or a quoted dash in a script, becomes an en dash (Question 19): the
    text needs a mark there, and the main repository's commit hook allows no em
    dash in any page."""
    if EM not in text:
        return text

    def rep(m):
        a, s1, s2, b = m.groups()
        if not (b and re.match(r"[\w($]", b)):
            return m.group(0)
        new = " - " if (s1 or s2) else ", "
        ctx = text[max(0, m.start() - 40): m.end() + 40].replace("\n", " ").strip()
        dash_log.append((where, ctx, new.strip()))
        return a + new
    text = DASH.sub(rep, text)
    for m in re.finditer(EM, text):
        ctx = text[max(0, m.start() - 40): m.end() + 40].replace("\n", " ").strip()
        dash_log.append((where, ctx, "– (placeholder)"))
    return text.replace(EM, "–")


# ---------- CSS scoping ----------

def blocks(css):
    css = re.sub(r"/\*.*?\*/", "", css, flags=re.S)
    out, i, n = [], 0, len(css)
    while i < n:
        j = css.find("{", i)
        if j < 0:
            break
        semi = css.find(";", i)
        if 0 <= semi < j:
            i = semi + 1
            continue
        depth, k = 1, j + 1
        while k < n and depth:
            depth += {"{": 1, "}": -1}.get(css[k], 0)
            k += 1
        out.append((css[i:j].strip(), css[j + 1:k - 1]))
        i = k
    return out


KEEP_ROOT_PROPS = {"color", "font-family", "font-size", "line-height", "letter-spacing"}


def scope_css(css, scope, drop):
    out = []
    for pre, body in blocks(css):
        if pre.startswith("@media") or pre.startswith("@supports"):
            inner = scope_css(body, scope, drop)
            if inner.strip():
                out.append(f"{pre} {{\n{inner}}}\n")
            continue
        if pre.startswith("@"):
            out.append(f"{pre} {{{body}}}\n")
            continue
        sels = []
        root_rule = False
        for sel in (s.strip() for s in pre.split(",")):
            if not sel:
                continue
            classes = set(re.findall(r"\.([\w-]+)", sel))
            if classes & drop:
                continue
            m = re.match(r"^(:root|html|body)\b(.*)$", sel)
            if m:
                rest = re.sub(r"^\s*body\b", "", m.group(2))
                if not rest.strip():
                    root_rule = True
                    sels.append("." + scope)
                    continue
                sel = rest.strip() if rest.startswith(" ") else rest
                if not sel:
                    continue
                if not rest.startswith(" "):
                    sels.append("." + scope + sel)
                    continue
            bare = not re.search(r"[.#\[]", re.sub(r"::?[\w-]+(\([^)]*\))?", "", sel))
            if bare:
                continue
            sels.append(f".{scope} {sel}")
        if not sels:
            continue
        if root_rule:
            props = [p for p in body.split(";") if p.strip() and (p.strip().startswith("--") or p.split(":")[0].strip() in KEEP_ROOT_PROPS)]
            if not props:
                continue
            body = ";".join(props) + ";"
        out.append(",\n".join(sels) + " {" + body.rstrip() + "\n}\n")
    return "".join(out)


