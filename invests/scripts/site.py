def page_scripts(page, repo, scripts):
    r = rel(page, "")
    out = []
    for s in scripts:
        src = s["src"]
        if src:
            if src.startswith("http"):
                if src == CHARTJS:
                    out.append(f'<script src="{CHARTJS}" integrity="{CHARTJS_SRI}" crossorigin="anonymous"></script>')
                else:
                    out.append(f'<script src="{esc(src)}"></script>')
                continue
            if repo == "vix" and src == "data/vix.js":
                out.append(f'<script src="{VIX_FEED}"></script>')
                continue
            if repo == "leverage" and src == "js/main.js":
                continue  # only drove the old sidebar; the shell does this now
            name = src.split("/")[-1]
            out.append(f'<script src="{r}assets/js/{repo}/{name}"></script>')
        else:
            js = s["body"]
            if repo == "azqato.github.io":
                continue  # only drove the old azqato.com nav toggle
            if s["attrs"].get("type") == "application/ld+json":
                continue
            js = repoint_js(js)
            if repo == "vix":
                js = vix_inline(js)
            js = fix_dashes(js, f"{page} (inline script)")
            out.append(f"<script>{js}</script>")
    return "\n".join(out)


def vix_inline(js):
    """UI review, VIX pages. A reading saved by another VIX page less than 30
    minutes ago (vix.js's REFRESH_TTL) is the same live reading, so it shows
    LIVE, not CACHED; STALE still marks an old one. The Custom builder words
    its tier line like the Dashboard."""
    js = js.replace("setStatus(data.stale ? 'stale' : data.fromCache ? 'cached' : 'live');",
                    "setStatus(data.stale ? 'stale' : 'live'); // Azqato Invests: a fresh saved reading is live")
    js = js.replace("const { getTier, getAllocation }     = window.VixStrategy;",
                    "const { getTier, getAllocation, getTierLabel } = window.VixStrategy;")
    js = js.replace("el.textContent = `VIX ${vixValue.toFixed(2)} \u2192 Tier: ${tier.replace('tier', '')}`;",
                    "el.textContent = `VIX ${vixValue.toFixed(2)} \u2192 ${getTierLabel(tier)}`; // Azqato Invests: as on the Dashboard")
    return js


FEED_CLEAN = ("/* Azqato Invests: feed text is shown as HTML, so angle brackets are dropped from it. */\n"
              "function azqClean(v) { if (typeof v === 'string') return v.replace(/[<>]/g, '');"
              " if (v && typeof v === 'object') { for (var k in v) v[k] = azqClean(v[k]); } return v; }\n")


def repoint_js(js):
    js = re.sub(r'(["\'])data/', lambda m: m.group(1) + STOCKS_DATA, js)
    if "await res.json()" in js and "fetch(" in js and "VixStrategy" not in js:
        js = FEED_CLEAN + js.replace("await res.json()", "azqClean(await res.json())")
    return js


def copy_scripts():
    pairs = [("stocks", SRC / "stocks/script.js"), ("stocks", SRC / "stocks/screener.js")]
    pairs += [("vix", p) for p in sorted((SRC / "vix/assets/js").glob("*.js"))]
