FONT_SIZE = re.compile(r"font-size:\s*([\d.]+)(px|rem)")


def min_font(css):
    """No source text under 12px (UI review): px sizes below 12 and rem sizes
    below 0.75 are raised to that floor."""
    def fix(m):
        v, unit = float(m.group(1)), m.group(2)
        if unit == "px" and v < 12:
            return "font-size: 12px"
        if unit == "rem" and v < 0.75:
            return "font-size: 0.75rem"
        return m.group(0)
    return FONT_SIZE.sub(fix, css)


