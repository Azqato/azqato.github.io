def build_page(entry, search):
    page, src, label, group, kind, parent = entry
    repo = src.split("/")[0]
    soup, body, scripts, styles, desc = extract(src, page)
    if repo == "azqato.github.io":
        part = "home" if page == "index.html" else "resources"
        nodes = split_invests(body, part, soup, page)
        if part == "resources":
            desc = "Curated investing resources from Azqato Invests: platforms, careers, screeners, education, data and news, in 15 categories. Some links are referral links."
    else:
        nodes = list(body.children)
    article = BeautifulSoup("", "html.parser")
    wrap = article.new_tag("div", attrs={"class": f"site-src {SCOPE[repo]}"})
    article.append(wrap)
    for n in nodes:
        wrap.append(n.extract() if hasattr(n, "extract") else n)
    if page in ATLAS:
        first = wrap.find("section")
        first.insert_before(BeautifulSoup(atlas_box(page), "html.parser"))
    if page == "resources/faq.html":
        h1 = wrap.find("h1")
        anchor = h1.find_parent("section") or h1
        anchor.insert_after(BeautifulSoup(FAQ_FILTER, "html.parser"))
    notes = merge_footers(wrap, repo)
    if page == "vix/custom.html":
        # The reading and tier first (UI review), then the ticker inputs, then the
        # chart and table they drive (author's request, 2026-10-02).
        wrap.find(id="chart-section").insert_before(wrap.find(id="customize").extract())
    dash_tree(wrap, page)
    ensure_ids(wrap)
    title = TITLES.get(page, f"{label} - {BRAND}")
    title = fix_dashes(title, page + " (title)")
    desc = fix_dashes(desc, page + " (description)")
    inline_css = "".join(scope_css(s, SCOPE[repo], set(CHROME[repo]["css_drop"])) for s in styles)
    inline_css = min_font(fix_dashes(inline_css, page + " (inline style)"))
    extra = [] if repo == "azqato.github.io" else [f"src-{repo}.css"]
    toc = "" if kind != "doc" else """<aside class="pp-toc" aria-labelledby="pp-toc-title">
  <p class="pp-toc-title" id="pp-toc-title">On this page</p>
  <ul class="pp-toc-list" id="pp-toc-list"></ul>
</aside>
"""
    content = str(article).replace(" viewbox=", " viewBox=")  # html.parser lowercases SVG attributes
    r = rel(page, "")
    doc = (head(page, title, desc, kind, SCOPE[repo], extra, inline_css)
           + f'<body class="pp-page site-page is-{kind}" data-root="{r}">\n'
           + topbar(page)
           + '<div class="pp-shell">\n' + sidebar(page)
           + '<main class="pp-main" id="pp-main" tabindex="-1">\n' + crumbs(page, label, group, parent)
           + f'<article class="pp-article" id="pp-article">\n{content}\n</article>\n'
           + pager(page) + "</main>\n" + toc + "</div>\n"
           + footer(page, fix_dashes(notes, page + " (footer)"))
           + f'<script src="{r}assets/js/site.js"></script>\n'
           + page_scripts(page, repo, scripts) + "\n</body>\n</html>\n")
    out = ROOT / page
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(doc, encoding="utf-8", newline="\n")
    index_page(page, label, group, wrap, search)


def merge_footers(wrap, repo):
    """One footer per page (UI review). The source footers that only repeat the
    site footer ("Built by Azqato", "Educational use only. Not financial advice.")
    stay in the page, hidden (class site-dup). The VIX pages' disclaimer and
    copyright lines move into the site footer; their call-to-action stays."""
    notes = []
    for f in wrap.select(".src-footer"):
        disc = f.select_one(".footer-disclaimer")
        if repo == "vix" and disc:
            for p in disc.find_all("p"):
                p["class"] = p.get("class", []) + ["site-footer-note"]
                if p.get_text(" ", strip=True).startswith("Built by"):
                    p["class"] = p["class"] + ["site-dup"]
                notes.append(str(p))
            disc.decompose()
        elif not f.select_one(".footer-cta"):
            f["class"] = f.get("class", []) + ["site-dup"]
    return "".join("\n    " + n for n in notes)


def index_page(page, label, group, wrap, search):
    pi = len(search["pages"])
    search["pages"].append({"u": page, "t": label if page != "index.html" else "Home", "g": group or "Home"})
    entry = {"p": pi, "h": label, "a": "", "x": ""}
    for el in wrap.find_all(["h1", "h2", "h3", "p", "li", "td", "th", "dt", "dd", "button", "figcaption", "summary"]):
        if el.name in ("h2", "h3") and el.get("id"):
            search["entries"].append(entry)
            entry = {"p": pi, "h": el.get_text(" ", strip=True), "a": el["id"], "x": ""}
        elif el.name != "h1" and not el.find(["p", "li", "td", "dt", "dd"]):
            entry["x"] += " " + el.get_text(" ", strip=True)
    search["entries"].append(entry)


