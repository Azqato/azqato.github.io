/*
 * The shell's behavior on every page: the navigation drawer, "On this page",
 * site search and the FAQ filter. Adapted from Template Interface's
 * documentation-site script.js (commit ed840da) with its hash routing, code
 * tabs and feedback form taken out, since every page here is its own file.
 */
(function () {
  "use strict";

  var body = document.body;
  var ROOT = body.getAttribute("data-root") || "";
  var article = document.getElementById("pp-article");
  var POPULAR = ["tools/screener.html", "strategies/vix.html", "learn/metrics.html", "faq.html"];

  function esc(s) {
    return String(s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", "\"": "&quot;", "'": "&#39;" }[c];
    });
  }

  function plain(el) {
    return el.textContent.replace(/\s+/g, " ").trim();
  }

  /* ---------- On this page ---------- */

  var tocList = document.getElementById("pp-toc-list");
  var tocLinks = [];
  var headings = [];

  function buildToc() {
    if (!tocList || !article) return;
    headings = [].slice.call(article.querySelectorAll("h2[id]")).filter(function (h) {
      return !h.closest(".modal-backdrop, [hidden], .accordion-body");
    });
    if (!headings.length) {
      tocList.closest(".pp-toc").hidden = true;
      return;
    }
    var inline = document.createElement("details");
    inline.className = "pp-toc-inline";
    var summary = document.createElement("summary");
    summary.textContent = "On this page";
    inline.appendChild(summary);
    var inlineList = document.createElement("ul");
    inline.appendChild(inlineList);
    headings.forEach(function (h) {
      [tocList, inlineList].forEach(function (list) {
        var li = document.createElement("li");
        var a = document.createElement("a");
        a.href = "#" + h.id;
        a.textContent = plain(h);
        li.appendChild(a);
        list.appendChild(li);
        if (list === tocList) tocLinks.push(a);
      });
    });
    var first = article.querySelector(".site-src > *");
    if (headings.length > 1 && first) first.parentNode.insertBefore(inline, first.nextSibling);
    markToc();
  }

  // The last section heading above the top fifth of the window is "current".
  function markToc() {
    if (!headings.length) return;
    var line = Math.min(160, window.innerHeight * 0.2);
    var at = 0;
    headings.forEach(function (h, i) {
      if (h.getBoundingClientRect().top <= line) at = i;
    });
    if (window.innerHeight + window.scrollY >= document.documentElement.scrollHeight - 2) {
      var visible = headings.filter(function (h) { return h.getBoundingClientRect().top < window.innerHeight; });
      if (visible.length) at = headings.indexOf(visible[visible.length - 1]);
    }
    tocLinks.forEach(function (a, i) {
      if (i === at) a.setAttribute("aria-current", "location");
      else a.removeAttribute("aria-current");
    });
  }

  var ticking = false;
  window.addEventListener("scroll", function () {
    if (ticking) return;
    ticking = true;
    requestAnimationFrame(function () { ticking = false; markToc(); });
  }, { passive: true });
  window.addEventListener("resize", markToc);
  buildToc();

  /* ---------- Navigation drawer (below 900px) ---------- */

  var menuBtn = document.getElementById("pp-menu-btn");
  var navClose = document.getElementById("pp-nav-close");
  var scrim = document.getElementById("pp-scrim");
  var narrow = window.matchMedia("(max-width: 900px)");
  var behind = [".site-skip", ".site-azqato", ".pp-top", "#pp-main", ".pp-toc", ".pp-footer"].map(function (s) {
    return document.querySelector(s);
  }).filter(Boolean);

  function openNav() {
    body.classList.add("is-nav-open");
    scrim.hidden = false;
    menuBtn.setAttribute("aria-expanded", "true");
    behind.forEach(function (el) { el.inert = true; });
    navClose.focus();
  }

  function closeNav(returnFocus) {
    if (!body.classList.contains("is-nav-open")) return;
    body.classList.remove("is-nav-open");
    scrim.hidden = true;
    menuBtn.setAttribute("aria-expanded", "false");
    behind.forEach(function (el) { el.inert = false; });
    if (returnFocus) menuBtn.focus();
  }

  menuBtn.addEventListener("click", openNav);
  navClose.addEventListener("click", function () { closeNav(true); });
  scrim.addEventListener("click", function () { closeNav(true); });
  document.addEventListener("keydown", function (event) {
    if (event.key === "Escape" && body.classList.contains("is-nav-open")) closeNav(true);
  });
  narrow.addEventListener("change", function () { if (!narrow.matches) closeNav(false); });

  /* ---------- Search ---------- */

  // The index (assets/js/search-index.js, generated by tools/site.py) loads on
  // first use, so pages don't download every page's text up front.
  var index = null;
  var loading = false;

  function loadIndex(done) {
    if (index) return done();
    if (window.SITE_INDEX) {
      index = window.SITE_INDEX;
      return done();
    }
    if (loading) return;
    loading = true;
    var s = document.createElement("script");
    s.src = ROOT + "assets/js/search-index.js";
    s.onload = function () { index = window.SITE_INDEX; loading = false; done(); };
    s.onerror = function () { loading = false; resultsHead.textContent = "Search couldn't load. Try again."; };
    document.head.appendChild(s);
  }

  var dialog = document.getElementById("pp-search");
  var openBtn = document.getElementById("pp-search-open");
  var closeBtn = document.getElementById("pp-search-close");
  var input = document.getElementById("pp-search-input");
  var results = document.getElementById("pp-results");
  var resultsHead = document.getElementById("pp-results-head");
  var count = document.getElementById("pp-search-count");
  var empty = document.createElement("p");
  empty.className = "pp-search-empty";
  empty.hidden = true;
  results.parentNode.insertBefore(empty, results.nextSibling);

  var shown = [];
  var active = -1;
  var countTimer;

  function mark(text, terms) {
    var out = esc(text);
    terms.forEach(function (t) {
      var re = new RegExp("(" + esc(t).replace(/[.*+?^${}()|[\]\\]/g, "\\$&") + ")", "ig");
      out = out.replace(re, "<mark>$1</mark>");
    });
    return out;
  }

  function snippet(text, terms) {
    var low = text.toLowerCase();
    var at = -1;
    terms.forEach(function (t) {
      var i = low.indexOf(t);
      if (i !== -1 && (at === -1 || i < at)) at = i;
    });
    if (at === -1) return text.length > 110 ? text.slice(0, 110).replace(/\s\S*$/, "") + "..." : text;
    var start = Math.max(0, at - 40);
    var end = Math.min(text.length, at + 90);
    var s = text.slice(start, end);
    if (start > 0) s = "..." + s.replace(/^\S*\s/, "");
    if (end < text.length) s = s.replace(/\s\S*$/, "") + "...";
    return s;
  }

  function search(q) {
    var terms = q.toLowerCase().split(/\s+/).filter(Boolean);
    var found = [];
    index.entries.forEach(function (e) {
      var page = index.pages[e.p];
      var head = e.h.toLowerCase();
      var title = page.t.toLowerCase();
      var text = e.x.toLowerCase();
      var score = 0;
      for (var i = 0; i < terms.length; i++) {
        var t = terms[i];
        var inHead = head.indexOf(t) !== -1;
        var inTitle = title.indexOf(t) !== -1;
        var hits = text.split(t).length - 1;
        if (!inHead && !inTitle && !hits) return;
        score += (inHead ? 10 : 0) + (inTitle ? 4 : 0) + Math.min(hits, 5);
      }
      if (!e.a) score += 2;
      found.push({ e: e, score: score });
    });
    found.sort(function (a, b) { return b.score - a.score; });
    return { terms: terms, list: found.slice(0, 8).map(function (f) { return f.e; }) };
  }

  function setActive(i) {
    var items = results.children;
    if (active > -1 && items[active]) items[active].setAttribute("aria-selected", "false");
    active = i;
    if (i > -1 && items[i]) {
      items[i].setAttribute("aria-selected", "true");
      input.setAttribute("aria-activedescendant", items[i].id);
      items[i].scrollIntoView({ block: "nearest" });
    } else {
      input.removeAttribute("aria-activedescendant");
    }
  }

  function paintResults() {
    if (!index) return;
    var q = input.value.trim();
    var terms = [];
    if (q) {
      var r = search(q);
      shown = r.list;
      terms = r.terms;
      resultsHead.textContent = shown.length ? "Results" : "No results";
    } else {
      shown = POPULAR.map(function (u) {
        var pi = index.pages.map(function (p) { return p.u; }).indexOf(u);
        return index.entries.filter(function (e) { return e.p === pi && !e.a; })[0];
      }).filter(Boolean);
      resultsHead.textContent = "Popular";
    }

    results.textContent = "";
    shown.forEach(function (e, i) {
      var p = index.pages[e.p];
      var li = document.createElement("li");
      li.id = "pp-opt-" + i;
      li.className = "pp-result";
      li.setAttribute("role", "option");
      li.setAttribute("aria-selected", "false");
      li.setAttribute("data-href", ROOT + p.u + (e.a ? "#" + e.a : ""));
      li.innerHTML =
        "<span class=\"pp-r-crumb\">" + esc(p.g) + " / " + esc(p.t) + "</span>" +
        "<span class=\"pp-r-title\">" + mark(e.h, terms) + "</span>" +
        "<span class=\"pp-r-snip\">" + mark(snippet(e.x, terms), terms) + "</span>";
      results.appendChild(li);
    });

    empty.hidden = !(q && !shown.length);
    if (!empty.hidden) {
      empty.textContent = "Nothing matches “" + q + "”. Try one word, like “PEG” or “VIX”.";
    }
    results.hidden = !shown.length;
    active = -1;
    setActive(shown.length ? 0 : -1);

    clearTimeout(countTimer);
    countTimer = setTimeout(function () {
      count.textContent = q ? (shown.length ? shown.length + (shown.length === 1 ? " result" : " results") : "No results") : "";
    }, 400);
  }

  function openSearch() {
    if (dialog.open) return;
    closeNav(false);
    dialog.showModal();
    resultsHead.textContent = index ? resultsHead.textContent : "Loading";
    loadIndex(paintResults);
    input.select();
  }

  function choose(i) {
    var li = results.children[i];
    if (!li) return;
    dialog.close();
    window.location.href = li.getAttribute("data-href");
  }

  openBtn.addEventListener("click", openSearch);
  closeBtn.addEventListener("click", function () { dialog.close(); });
  dialog.addEventListener("click", function (event) {
    if (event.target === dialog) dialog.close();
  });
  input.addEventListener("input", paintResults);
  input.addEventListener("keydown", function (event) {
    var n = results.children.length;
    if (event.key === "ArrowDown" && n) {
      event.preventDefault();
      setActive((active + 1) % n);
    } else if (event.key === "ArrowUp" && n) {
      event.preventDefault();
      setActive((active - 1 + n) % n);
    } else if (event.key === "Enter") {
      event.preventDefault();
      if (active > -1) choose(active);
    }
  });
  results.addEventListener("mousemove", function (event) {
    var li = event.target.closest(".pp-result");
    if (li) {
      var i = [].indexOf.call(results.children, li);
      if (i !== active) setActive(i);
    }
  });
  results.addEventListener("click", function (event) {
    var li = event.target.closest(".pp-result");
    if (li) choose([].indexOf.call(results.children, li));
  });

  document.addEventListener("keydown", function (event) {
    var el = document.activeElement;
    var typing = el && (/^(INPUT|TEXTAREA|SELECT)$/.test(el.tagName) || el.isContentEditable);
    if ((event.ctrlKey || event.metaKey) && event.key.toLowerCase() === "k") {
      event.preventDefault();
      openSearch();
    } else if (event.key === "/" && !typing && !dialog.open) {
      event.preventDefault();
      openSearch();
    }
  });

  /* ---------- FAQ filter (help-center's search-as-you-type, D8) ---------- */

  // A link to one answer (faq.html#answer-...) opens that answer.
  function openLinked() {
    var id = decodeURIComponent(location.hash.slice(1));
    var target = id && document.getElementById(id);
    var item = target && target.closest(".accordion-item");
    if (!item) return;
    var trigger = item.querySelector(".accordion-trigger");
    if (trigger && trigger.getAttribute("aria-expanded") !== "true") trigger.click();
    item.scrollIntoView();
  }
  window.addEventListener("load", openLinked);
  window.addEventListener("hashchange", openLinked);

  var filter = document.getElementById("faq-filter");
  if (filter) {
    var items = [].slice.call(article.querySelectorAll(".accordion-item"));
    var status = document.getElementById("faq-filter-count");
    var timer;
    filter.addEventListener("input", function () {
      var terms = filter.value.toLowerCase().split(/\s+/).filter(Boolean);
      var n = 0;
      items.forEach(function (item) {
        var text = item.textContent.toLowerCase();
        var hit = terms.every(function (t) { return text.indexOf(t) !== -1; });
        item.hidden = !hit;
        if (hit) n++;
      });
      // Hide a section's heading when none of its questions match.
      [].forEach.call(article.querySelectorAll(".site-src section"), function (sec) {
        var qs = sec.querySelectorAll(".accordion-item");
        if (!qs.length) return;
        var any = [].some.call(qs, function (q) { return !q.hidden; });
        sec.hidden = !any;
      });
      clearTimeout(timer);
      timer = setTimeout(function () {
        status.textContent = terms.length ? n + (n === 1 ? " question matches" : " questions match") : "";
      }, 300);
    });
  }

  /* ---------- VIX tables as cards on phones ----------
     Each cell gets its column heading as data-label, which the phone layout
     in site.css shows beside the value. The tool pages fill their tables
     after loading, so new rows are labeled as they arrive. */

  function labelTable(table) {
    var heads = Array.prototype.map.call(table.querySelectorAll("thead th"), plain);
    Array.prototype.forEach.call(table.querySelectorAll("tbody tr"), function (tr) {
      Array.prototype.forEach.call(tr.children, function (td, i) {
        if (heads[i] && !td.hasAttribute("data-label")) td.setAttribute("data-label", heads[i]);
      });
    });
  }

  Array.prototype.forEach.call(document.querySelectorAll(".src-vix table.table-styled"), function (table) {
    labelTable(table);
    if (window.MutationObserver) {
      new MutationObserver(function () { labelTable(table); }).observe(table, { childList: true, subtree: true });
    }
  });
})();
